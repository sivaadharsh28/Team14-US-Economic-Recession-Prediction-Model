"""#Recursive Cross Validation Model - To Test Accuracy of ADR Model"""

import numpy as np
import pandas as pd
import statsmodels.api as sm
from sklearn.metrics import mean_squared_error
import matplotlib.pyplot as plt

y = quarterly_selected_data['GDPC1_diff'].shift(-1)

X_lag1 = quarterly_selected_data[['GDPCTPI_diff_lag1', 'INDPRO_diff_lag1', 'IPFINAL_diff_lag1', 'IPCONGD_diff_lag1',
                                  'IPMAT_diff_lag1', 'PAYEMS_diff_lag1', 'MANEMP_diff_lag1', 'LNS14000012_diff_lag1',
                                  'UEMPLT5_diff_lag1', 'PCECC96_pct_change_lag1', 'CMRMTSPLx_pct_change_lag1',
                                  'GS10_pct_change_lag1', 'TB3MS_pct_change_lag1', 'UNRATE_lag1', 'GS10TB3Mx_lag1',
                                  'BAA10YM_lag1']]

X_lag1 = sm.add_constant(X_lag1)

X_lag1.dropna(inplace=True)
y = y.loc[X_lag1.index]

initial_train_size = int(len(X_lag1) * 0.8)

actual_values = []
predicted_values = []
test_periods = []

for i in range(initial_train_size, len(X_lag1) - 1):
    X_train = X_lag1.iloc[:i]
    y_train = y.iloc[:i]

    X_test = X_lag1.iloc[i].values.reshape(1, -1)
    y_test = y.iloc[i]

    adl_model_lag1 = sm.OLS(y_train, X_train).fit()

    y_pred = adl_model_lag1.predict(X_test)[0]

    actual_values.append(y_test)
    predicted_values.append(y_pred)

    test_periods.append(X_lag1.index[i])

rmse_lag1 = np.sqrt(mean_squared_error(actual_values, predicted_values))

print(f"Recursive Cross-Validation RMSE for ADL Model (Lag 1): {rmse_lag1:.4f}")

plt.figure(figsize=(10, 5))
plt.plot(test_periods, actual_values, label="Actual GDP Growth (GDPC1_diff)", marker='o', linestyle='-')
plt.plot(test_periods, predicted_values, label="Predicted GDP Growth (ADL Lag 1)", marker='s', linestyle='--')
plt.xlabel("Quarter")
plt.ylabel("GDP Growth Difference")
plt.title("Recursive Cross-Validation: Actual vs. Predicted GDP Growth (Lag 1)")
plt.legend()
plt.grid()
plt.xticks(rotation=45)
